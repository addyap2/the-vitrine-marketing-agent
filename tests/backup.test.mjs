import test from 'node:test';
import assert from 'node:assert/strict';
import {parseBackup, makeBackup} from '../lib/backup.ts';
const campaign={id:'c1',name:'Campagne',objective:'Demandes',audience:'Commerçants',status:'Idée'};
const draft={id:'d1',title:'Post',agent:'social',content:'Bonjour',status:'Brouillon',date:'2026-11-23',created:'2026-11-23T10:00:00Z',campaign:'c1'};
const json=(drafts=[draft],campaigns=[campaign])=>JSON.stringify(makeBackup(drafts,campaigns));
test('valid backup round-trips',()=>assert.deepEqual(parseBackup(json()),{drafts:[draft],campaigns:[campaign]}));
test('rejects invalid JSON',()=>assert.throws(()=>parseBackup('{'),/JSON invalide/));
test('rejects incompatible version',()=>assert.throws(()=>parseBackup('{"version":1,"drafts":[],"campaigns":[]}'),/Version/));
test('rejects duplicate draft ids',()=>assert.throws(()=>parseBackup(json([draft,draft])),/double/));
test('rejects nonexistent campaign reference',()=>assert.throws(()=>parseBackup(json([draft],[])),/introuvable/));
test('rejects impossible dates',()=>assert.throws(()=>parseBackup(json([{...draft,date:'2026-02-30'}])),/incorrectes/));
test('accepts leap day',()=>assert.equal(parseBackup(json([{...draft,date:'2028-02-29'}])).drafts.length,1));
test('rejects excessive backup',()=>assert.throws(()=>parseBackup(' '.repeat(5_000_001)),/volumineuse/));
test('rejects oversized content',()=>assert.throws(()=>parseBackup(json([{...draft,content:'x'.repeat(100001)}])),/incorrectes/));